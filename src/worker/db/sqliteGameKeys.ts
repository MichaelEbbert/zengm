// Shared stat key lists used by both writeGameToSqlite (write) and getCopies/games (read).
// Insert underscore before a lowercase/digit followed by uppercase: pssYds → pss_yds, koTB → ko_tb
export const toSnake = (s: string): string =>
	s.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();

